/**
 * Regenerates the "Shiv Radium" watermark tile and writes it, base64-encoded,
 * into `src/server/uploads/watermarkTile.ts`.
 *
 * The tile is a small transparent PNG with the brand name set diagonally. It is
 * baked once here (not rasterised at request time) because tiling a ready PNG
 * needs no fonts, whereas SVG `<text>` relies on system fonts a serverless
 * runtime may not ship. The media route (`/api/media/[id]`) tiles it across
 * product photos to stamp the whole image.
 *
 *   Run:  npx tsx scripts/make-watermark-tile.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import sharp from "sharp";

const TILE_WIDTH = 300;
const TILE_HEIGHT = 190;

const tileSvg = `<svg width="${TILE_WIDTH}" height="${TILE_HEIGHT}" xmlns="http://www.w3.org/2000/svg">
  <g transform="translate(${TILE_WIDTH / 2} ${TILE_HEIGHT / 2}) rotate(-28)">
    <text text-anchor="middle" dominant-baseline="middle"
      font-family="Arial, Helvetica, sans-serif" font-weight="700" font-size="30"
      letter-spacing="1"
      fill="#ffffff" fill-opacity="0.55"
      stroke="#000000" stroke-opacity="0.22" stroke-width="1.1"
      paint-order="stroke">Shiv Radium</text>
  </g>
</svg>`;

async function main() {
  const png = await sharp(Buffer.from(tileSvg)).png().toBuffer();
  const b64 = png.toString("base64");

  const out = `// GENERATED by scripts/make-watermark-tile.ts — do not edit by hand.
// The "Shiv Radium" watermark tile (${TILE_WIDTH}×${TILE_HEIGHT} transparent PNG)
// as base64, so the media route can stamp product photos without reading a file
// or rasterising fonts at request time.
export const WATERMARK_TILE_B64 =
  "${b64}";
`;

  const target = join(process.cwd(), "src", "server", "uploads", "watermarkTile.ts");
  writeFileSync(target, out);
  console.log(`Wrote ${target} (${png.length} PNG bytes, ${b64.length} base64 chars).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
